// A local, repeatable demonstration with isolated sample data for Mario and Ellen.
import { mkdir, mkdtemp } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { startLocalReviewPreview } from './reviews-dev.mjs';
import { projectRoot } from './build-site.mjs';

const artifacts = join(projectRoot,'.local/admin-review-2026-10-15');
await mkdir(artifacts,{recursive:true});
const directory = await mkdtemp(join(projectRoot,'.local/admin-demo-'));
const preview = await startLocalReviewPreview({port:0,directory});
let browser, context, page;
const errors = [];
try {
  browser = await chromium.launch({headless:true,slowMo:110,...(process.platform==='win32'?{channel:'msedge'}:{})});
  context = await browser.newContext({viewport:{width:1280,height:900},recordVideo:{dir:artifacts,size:{width:1280,height:900}}});
  page = await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('dialog',dialog=>dialog.accept());
  page.setDefaultTimeout(15000);
  const pause = milliseconds => page.waitForTimeout(milliseconds);
  const step = index => page.locator('#editor-steps button').nth(index-1).click();
  async function shot(name) { await page.screenshot({path:join(artifacts,name+'.png'),fullPage:false}); }
  const form = new FormData();
  for (const [key,value] of Object.entries({name:'Viajera de demostración',country:'El Salvador',rating:'5',comment:'Conocimos lugares maravillosos y disfrutamos la atención del equipo durante todo el recorrido.',lang:'es',tourSlug:'',submissionId:crypto.randomUUID(),consent:'true',turnstileToken:'local-test',website:''})) form.append(key,value);
  const submitted = await fetch(preview.url+'/reviews-api/submit',{method:'POST',headers:{Origin:preview.url},body:form});
  if (submitted.status!==201) throw new Error('No se preparó la reseña local de demostración: '+await submitted.text());
  await page.goto(preview.url+'/admin/');
  await page.getByLabel('Correo electrónico',{exact:true}).fill('pruebas@local.invalid');
  await page.getByLabel('Contraseña',{exact:true}).fill('resenas-local');
  await page.getByRole('button',{name:'Entrar al panel',exact:true}).click();
  await page.locator('#dashboard-section').waitFor({state:'visible'});
  await page.evaluate(()=>window.scrollTo(0,160));
  await shot('01-inicio'); await pause(2300);
  await page.getByRole('link',{name:'Administrar tours',exact:true}).click();
  await page.locator('.tour-item').first().getByRole('button',{name:'Editar',exact:true}).click();
  await page.locator('#editor-fields').scrollIntoViewIfNeeded();
  await shot('02-editor-tour'); await pause(1500);
  await page.getByLabel('Descripción breve',{exact:true}).fill('Un recorrido por la historia, la cultura y los sabores de San Salvador.');
  await page.getByText('Ver cómo va quedando',{exact:true}).click();
  await page.locator('#live-content-preview').scrollIntoViewIfNeeded();
  await page.getByText('Vista previa actualizada. Sin publicar.',{exact:true}).waitFor();
  await pause(1800);
  await page.getByText('Ver cómo va quedando',{exact:true}).click();
  await step(2);
  await page.locator('.gallery-editor').scrollIntoViewIfNeeded();
  await page.locator('.gallery-editor img').first().evaluate(image=>image.decode());
  await shot('03-fotos-tour'); await pause(1500);
  const cover = page.getByRole('button',{name:'Usar como portada',exact:true}).first();
  if (await cover.count()) await cover.click();
  await step(3); await pause(1400);
  await page.getByRole('button',{name:'Guardar borrador',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#content-message').textContent.startsWith('Borrador guardado'));
  await step(4);
  await page.getByText('Vista previa actualizada. Sin publicar.',{exact:true}).waitFor();
  const frame = page.frameLocator('#content-preview iframe');
  await frame.locator('#modal-main-image').evaluate(image=>image.decode());
  const styled = await frame.locator('.modal-content').evaluate(element=>getComputedStyle(element).maxWidth!=='none');
  if (!styled) throw new Error('La página pública no terminó de cargar sus estilos para el video.');
  await page.locator('#content-preview').scrollIntoViewIfNeeded();
  await pause(2000); await shot('04-vista-previa-tour');
  await page.getByRole('button',{name:'Celular',exact:true}).click();
  await pause(2000); await shot('05-vista-previa-celular');
  await page.locator('.admin-header a[href="index.html"]').last().click();
  await page.getByRole('link',{name:'Administrar bienes raíces',exact:true}).click();
  await page.locator('.tour-item').filter({hasText:'Art Haus'}).getByRole('button',{name:'Editar',exact:true}).click();
  await page.locator('#editor-fields').scrollIntoViewIfNeeded();
  await pause(1700); await shot('06-editor-art-haus');
  await step(2);
  await page.locator('.gallery-editor').scrollIntoViewIfNeeded();
  await pause(2000); await shot('07-fotos-art-haus');
  await step(4);
  await page.getByText('Vista previa actualizada. Sin publicar.',{exact:true}).waitFor();
  await page.locator('#content-preview').scrollIntoViewIfNeeded();
  await pause(1800); await shot('08-vista-previa-art-haus');
  await page.locator('.admin-header a[href="index.html"]').last().click();
  await page.getByRole('link',{name:'Administrar reseñas',exact:true}).click();
  await page.locator('.admin-review').waitFor();
  await page.locator('.admin-review').scrollIntoViewIfNeeded();
  await pause(2400); await shot('09-resenas');
  await page.locator('.admin-review').getByRole('button',{name:'Publicar',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#admin-message').textContent.includes('publicada'));
  await page.locator('#status-filter').selectOption('approved');
  await page.locator('.admin-review').waitFor(); await pause(1600);
  await page.locator('.admin-header a[href="index.html"]').last().click();
  await page.evaluate(()=>window.scrollTo(0,160)); await pause(1400);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0)); await shot('10-inicio-celular');
  await page.getByRole('link',{name:'Administrar tours',exact:true}).click();
  await page.locator('.tour-item').first().getByRole('button',{name:'Editar',exact:true}).click();
  await page.getByLabel('Título',{exact:true}).scrollIntoViewIfNeeded(); await shot('11-editor-celular');
  if (errors.length) throw new Error(errors.join('\n'));
  const video = page.video();
  await context.close(); context = null;
  await video.saveAs(join(artifacts,'panel-demostracion.webm'));
  console.log('Video y capturas preparados: '+artifacts);
} finally {
  await context?.close(); await browser?.close();
  preview.server.closeAllConnections();
  await new Promise(resolve=>preview.server.close(resolve));
}
