import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { contentSeedSQL } from './content-seed.mjs';
const owner = '10000000-0000-4000-8000-000000000001';
const other = '20000000-0000-4000-8000-000000000002';
test('SQL protects drafts, checks actor, keeps public snapshots and rejects stale edits', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create schema storage; create table auth.users(id uuid primary key);
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      insert into auth.users values ('${owner}'),('${other}');`);
    await db.exec(await readFile(new URL('../supabase/schemas/content.sql', import.meta.url), 'utf8'));
    await db.query('insert into public.content_admins(user_id) values ($1)', [owner]);
    const write = (actor, action, version, title) => db.query('select public.write_site_content($1,$2,$3,$4::jsonb,$5,$6) as result', [actor, 'test-tour', 'tour', JSON.stringify({ id: 'test-tour', slug: 'test-tour', title: { es: title }, images: ['assets/img/slide_0.jpg'] }), action, version]);
    await write(owner, 'publish', 0, 'Original');
    await write(owner, 'save', 1, 'Borrador');
    const row = (await db.query('select * from public.content_documents')).rows[0];
    assert.equal(row.draft.title.es, 'Borrador'); assert.equal(row.published.title.es, 'Original');
    await assert.rejects(write(owner, 'save', 1, 'Desactualizado'), /content-conflict/);
    await assert.rejects(write(other, 'publish', 2, 'Sin permiso'), /content-forbidden/);
    await db.exec('set role anon');
    await assert.rejects(db.query('select * from public.content_documents'), /permission denied/);
    await assert.rejects(write(owner, 'publish', 2, 'Ataque'), /permission denied/);
    await db.exec('reset role; set role authenticated');
    await assert.rejects(db.query('select * from public.content_documents'), /permission denied/);
    await db.exec('reset role');
    await write(owner, 'hide', 2, '');
    assert.equal((await db.query('select status from public.content_documents')).rows[0].status, 'hidden');
    assert.equal((await db.query('select count(*)::int as n from public.content_audit')).rows[0].n, 3);
    const tours = JSON.parse(await readFile(new URL('../data/tours.json',import.meta.url))).tours;
    const seedSQL = contentSeedSQL(tours);
    await db.exec(seedSQL);
    const id = tours[0].id;
    await db.query("update public.content_documents set draft = jsonb_set(draft,'{title,es}','\"Edición del dueño\"'), published = jsonb_set(published,'{title,es}','\"Edición del dueño\"'), version=7 where id=$1",[id]);
    await db.exec(seedSQL);
    const preserved = (await db.query('select * from public.content_documents where id=$1',[id])).rows[0];
    assert.equal(preserved.published.title.es,'Edición del dueño'); assert.equal(preserved.version,7);
    const seeded = (await db.query("select published from public.content_documents where kind='tour' and id <> 'test-tour' order by (published->>'sortOrder')::int")).rows.map(row=>row.published.id);
    assert.deepEqual(seeded,tours.map(t=>t.id));
    const partner = { id: 'partner-art-haus', slug: 'art-haus', type: 'lodging', name: { es: 'Art Haus' }, shortDescription: { es: 'Alojamiento aliado' }, description: { es: 'Arte y hospedaje' }, images: ['assets/img/slide_0.jpg'], sortOrder: 0 };
    const writePartner = (action, version, data = partner, id = partner.id, kind = 'partner') => db.query('select public.write_site_content($1,$2,$3,$4::jsonb,$5,$6) as result', [owner, id, kind, JSON.stringify(data), action, version]);
    await writePartner('save', 0, { id: partner.id, slug: partner.slug });
    assert.equal((await db.query('select published from public.content_documents where id=$1', [partner.id])).rows[0].published, null);
    await assert.rejects(writePartner('publish', 1, { ...partner, description: {} }), /content-invalid/);
    await assert.rejects(writePartner('publish', 1, { ...partner, slug: 'changed' }), /content-invalid/);
    await assert.rejects(writePartner('save', 0, { ...partner, id: 'invalid' }, 'invalid'), /content-invalid/);
    await writePartner('publish', 1);
    await writePartner('save', 2, { ...partner, name: { es: 'Borrador del aliado' } });
    assert.equal((await db.query('select published from public.content_documents where id=$1', [partner.id])).rows[0].published.name.es, 'Art Haus');
    await assert.rejects(writePartner('publish', 2), /content-conflict/);
    await writePartner('hide', 3);
    assert.equal((await db.query('select status from public.content_documents where id=$1', [partner.id])).rows[0].status, 'hidden');
    const partnerSQL = contentSeedSQL([], '', [partner]);
    await db.exec(partnerSQL);
    assert.equal((await db.query('select status from public.content_documents where id=$1', [partner.id])).rows[0].status, 'hidden', 'Reimport must not republish hidden owner content');
  } finally { await db.close(); }
});
