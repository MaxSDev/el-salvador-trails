import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {getCountryCallingCode,isSupportedCountry} from 'libphonenumber-js';
import {createRequire} from 'node:module';
const metadata=createRequire(import.meta.url)('libphonenumber-js/metadata.min.json');
import {COUNTRY_CODES} from '../supabase/functions/_shared/country-codes.mjs';

// Calling codes come from libphonenumber metadata (dev dependency only); the site ships a static copy.
export function dialCodes(){
  return Object.fromEntries(COUNTRY_CODES.filter(code=>code!=='OTHER'&&isSupportedCountry(code)).map(code=>[code,getCountryCallingCode(code)]));
}

// Keep browser copies derived from the same server contract. Tests check parity.
export async function syncPersonalizedContract(){
  const root=new URL('../',import.meta.url),dial=JSON.stringify(dialCodes());
  await writeFile(new URL('supabase/functions/_shared/dial-codes.mjs',root),'// Generated by scripts/sync-personalized-contract.mjs from libphonenumber-js metadata.\nexport const DIAL_CODES=Object.freeze('+dial+');\n');
  const source=await readFile(new URL('supabase/functions/_shared/personalized-fields.mjs',root),'utf8');
  const browser=source.replace("import { COUNTRY_CODES } from './country-codes.mjs';",'var COUNTRY_CODES=window.ESTNationalityCodes;').replace("import { DIAL_CODES } from './dial-codes.mjs';",'var DIAL_CODES=window.ESTDialCodes;').replace(/^export /gm,'');
  await writeFile(new URL('js/personalized-rules.js',root),'// Generated from personalized-fields.mjs; tested for parity.\n(function(){\n'+browser+'\nwindow.ESTPersonalizedFields={fieldIssues:fieldIssues,SUPPORT_OPTIONS:SUPPORT_OPTIONS,OTHER_EXPERIENCES:OTHER_EXPERIENCES};\n})();\n');
  await writeFile(new URL('js/nationality-codes.js',root),'// Generated from country-codes.mjs. Unicode CLDR 48; Unicode-3.0.\n// Copyright Unicode, Inc. See https://www.unicode.org/license.txt\nwindow.ESTNationalityCodes = Object.freeze('+JSON.stringify(COUNTRY_CODES)+');\n');
  // The first region libphonenumber lists for a shared code (+1 → US) is the one a typed "+1" selects.
  const main=Object.fromEntries(Object.entries(metadata.country_calling_codes).map(([code,regions])=>[code,regions[0]]));
  await writeFile(new URL('js/dial-codes.js',root),'// Generated from libphonenumber-js metadata by scripts/sync-personalized-contract.mjs.\nwindow.ESTDialCodes = Object.freeze('+dial+');\nwindow.ESTDialMain = Object.freeze('+JSON.stringify(main)+');\n');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await syncPersonalizedContract();
